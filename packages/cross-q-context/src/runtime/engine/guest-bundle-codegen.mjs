// Emits the guest realm as data: every source string a host evals into the isolate, in
// order, plus the vendored require-able packages.
//
// A host that is not JavaScript cannot import these strings — but it can read this file.
// rq embeds it and evals the same strings in the same order in an in-process QuickJS, so
// the `rq.*` semantics stay owned here, in one place, rather than being reimplemented in
// Rust. That is the same argument that made rq host cross-q-context in the first place.
//
// Regenerate with `npm run build:guest-bundle`; CI fails if the committed copy drifts.
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';

const HERE = dirname(new URL(import.meta.url).pathname);
const dist = (p) => resolve(HERE, '../../../dist/runtime/engine/', p);

const { ISOLATE_SHIMS } = await import(dist('isolated/isolate-shim-order.js'));
const { CORE_GLOBALS_SHIM } = await import(dist('isolated/core-globals.js'));
const { REQUIRE_ISOLATE_SHIM } = await import(dist('isolated/shims/require.shim.js'));
const { RQ_ISOLATE_SHIM, RQ_COLLECT_EXPR, RQ_ITERATION_RESET_EXPR } = await import(dist('isolated/isolated-rq.js'));
const { DEPRECATION_ISOLATE_SHIM } = await import(dist('isolated/bridges/deprecation-bridge.js'));
const { RUN_REQUEST_ISOLATE_SHIM } = await import(dist('isolated/bridges/run-request-bridge.js'));
const { VENDOR_IIFES } = await import(dist('vendor-codegen/vendor-iifes.js'));
const { NEEDS_BRIDGE_MODULE_GLOBALS } = await import(dist('isolated/needs-bridge-globals.js'));
const { createImpossiblePackageError } = await import(dist('isolated/impossible-error.js'));
const { EXTERNAL_BUILTIN_PACKAGES, NODE_BUILTIN_PACKAGES } = await import(
  resolve(HERE, '../../../dist/runtime/definitions/builtInPackages/registry.js')
);
const { builtinModules } = await import('node:module');

// What `__rq_bundleRequire(id)` must answer, as data. The tiering lives in
// isolated-require.ts and is *classification*, not behaviour — so a non-JS host reads the
// answers here instead of re-deriving them, and cannot drift from this package's view of
// which packages are available.
const requireTable = {};
for (const [id, global] of Object.entries(NEEDS_BRIDGE_MODULE_GLOBALS)) {
  requireTable[id] = { kind: 'bridge', global };
}
for (const pkg of EXTERNAL_BUILTIN_PACKAGES) {
  if (pkg.safeModeClass === 'source_bundle' && pkg.globalName && VENDOR_IIFES[pkg.id] !== undefined) {
    requireTable[pkg.id] = { kind: 'iife', globalName: pkg.globalName };
  }
}
for (const pkg of NODE_BUILTIN_PACKAGES) {
  if (requireTable[pkg.id]) continue;
  if (pkg.safeModeClass === 'source_bundle' && pkg.globalName && VENDOR_IIFES[pkg.id] !== undefined) {
    requireTable[pkg.id] = { kind: 'iife', globalName: pkg.globalName };
  }
}

// The guided refusal, verbatim from the package. `%ID%` is the only substitution a host makes.
const REASONS = ['native_addon', 'live_socket', 'live_fs', 'asymmetric_crypto', 'other'];
const impossibleMessages = Object.fromEntries(
  REASONS.map((r) => [r, createImpossiblePackageError('%ID%', r).message]),
);
// Node builtins that are NOT in the table are refused before "package not found" —
// requiring `fs` should say why it cannot work, not that it doesn't exist.
const nodeBuiltins = builtinModules.filter((m) => !m.startsWith('_'));

// The order a host must eval in. `core` first (the guest's own globals), then the
// capability shims in their canonical order, then the require chain, then chai, then the
// rq.* namespace over both. Names are for diagnostics — a host reports which one threw.
const bundle = {
  $comment: 'Generated by src/runtime/engine/guest-bundle-codegen.mjs — do not edit by hand.',
  version: 1,
  evalOrder: [
    { name: 'core-globals', source: CORE_GLOBALS_SHIM },
    ...ISOLATE_SHIMS.map((source, i) => ({ name: `isolate-shim-${i}`, source })),
    { name: 'deprecation-shim', source: DEPRECATION_ISOLATE_SHIM },
    { name: 'run-request-shim', source: RUN_REQUEST_ISOLATE_SHIM },
    { name: 'require-chain', source: REQUIRE_ISOLATE_SHIM },
    { name: 'chai-load', source: 'globalThis.__rq_chai = globalThis.require("chai");' },
    { name: 'rq-namespace', source: RQ_ISOLATE_SHIM },
  ],
  // Drained after the script settles: one JSON string out of the isolate.
  collectExpr: RQ_COLLECT_EXPR,
  iterationResetExpr: RQ_ITERATION_RESET_EXPR,
  // require()-able package sources, loaded on demand by the require chain.
  vendor: VENDOR_IIFES,
  // How a host answers __rq_bundleRequire(id): the classification, as data.
  requireTable,
  impossibleMessages,
  nodeBuiltins,
  notFoundMessage: "Package '%ID%' not found.",
};

const out = resolve(HERE, '../../../../../crates/rq/assets/guest-bundle.json');
writeFileSync(out, JSON.stringify(bundle, null, 0) + '\n');
const kb = (JSON.stringify(bundle).length / 1024).toFixed(0);
console.log(`guest bundle → ${out} (${bundle.evalOrder.length} sources, ${Object.keys(bundle.vendor).length} vendored packages, ${kb} KB)`);

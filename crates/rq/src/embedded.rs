fn install_bridges<'js>(ctx: &Ctx<'js>, state: &Rc<RefCell<Collected>>) -> Result<()> {
    let g = ctx.globals();

    // console — the guest pre-serialises its args, so only strings cross.
    let sink = state.clone();
    g.set(
        "__rq_console",
        Function::new(ctx.clone(), move |level: String, args_json: String| {
            let args: Value =
                serde_json::from_str(&args_json).unwrap_or_else(|_| json!([args_json]));
            sink.borrow_mut().logs.push(json!({
                "level": level,
                "args": args,
                "timestamp": now_millis(),
            }));
        })?,
    )?;

    // Deprecation notices and timer-callback throws: recorded, never fatal.
    g.set(
        "__rq_deprecation",
        Function::new(ctx.clone(), |_identifier: String, _shimmed: bool| {})?,
    )?;
    let sink = state.clone();
    g.set(
        "__rq_timerError",
        Function::new(ctx.clone(), move |message: String| {
            sink.borrow_mut().logs.push(json!({
                "level": "error", "args": [message], "timestamp": now_millis(),
            }));
        })?,
    )?;

    // Timers. rq runs one short script at a time, so an armed timer is a bounded blocking
    // sleep rather than a scheduler: `await setTimeout(f, 50)` waits 50ms and continues.
    // Two timers therefore run in sequence rather than interleaved — the one place this host
    // is deliberately simpler than the event-loop one, and the shape of script that would
    // notice is not the shape anyone writes in a request.
    g.set(
        "__rq_setTimer",
        Function::new(ctx.clone(), move |_guest_id: i64, ms: f64| {
            let capped = ms.clamp(0.0, 2_000.0) as u64;
            std::thread::sleep(Duration::from_millis(capped));
        })?,
    )?;
    g.set(
        "__rq_clearTimer",
        Function::new(ctx.clone(), |_guest_id: i64| {})?,
    )?;

    // require() — answered from the classification the bundle carries.
    g.set(
        "__rq_bundleRequire",
        Function::new(ctx.clone(), |ctx: Ctx<'js>, id: String| {
            resolve_require(ctx, id)
        })?,
    )?;

    // The Node builtins the shims call out to.
    g.set("__rq_buffer", Function::new(ctx.clone(), buffer_bridge)?)?;
    g.set("__rq_crypto", Function::new(ctx.clone(), crypto_bridge)?)?;
    g.set("__rq_zlib", Function::new(ctx.clone(), zlib_bridge)?)?;
    g.set(
        "__rq_util_inspect",
        Function::new(ctx.clone(), util_inspect_bridge)?,
    )?;

    // fetch + rq.sendRequest, both on ureq.
    g.set("__rq_fetch", Function::new(ctx.clone(), fetch_bridge)?)?;
    g.set(
        "__rq_runRequest",
        Function::new(ctx.clone(), run_request_bridge)?,
    )?;

    // The cookie jar: in-memory for the run, which is what a one-shot CLI can honestly offer.
    let sink = state.clone();
    g.set(
        "__rq_cookies",
        Function::new(ctx.clone(), move |ctx: Ctx<'js>, args: Object<'js>| {
            cookie_bridge(ctx, args, &sink)
        })?,
    )?;

    Ok(())
}

/// The host half of the require chain. The tiering is the bundle's; this just answers.
fn resolve_require<'js>(ctx: Ctx<'js>, id: String) -> rquickjs::Result<Object<'js>> {
    let b = bundle();
    let out = Object::new(ctx.clone())?;
    if let Some(entry) = b.require_table.get(&id) {
        if entry["kind"] == "bridge" {
            out.set("kind", "bridge")?;
            out.set("global", entry["global"].as_str().unwrap_or_default())?;
        } else {
            out.set("kind", "iife")?;
            out.set(
                "globalName",
                entry["globalName"].as_str().unwrap_or_default(),
            )?;
            out.set("code", b.vendor[&id].as_str().unwrap_or_default())?;
        }
        return Ok(out);
    }
    let bare = id.strip_prefix("node:").unwrap_or(&id);
    let message = if b.node_builtins.iter().any(|m| m == bare) {
        // A refused builtin says why it cannot work, rather than that it does not exist.
        b.impossible["other"]
            .as_str()
            .unwrap_or_default()
            .replace("%ID%", bare)
    } else {
        format!("Package '{id}' not found.")
    };
    Err(throw(ctx, &message))
}

fn throw(ctx: Ctx<'_>, message: &str) -> rquickjs::Error {
    match rquickjs::String::from_str(ctx.clone(), message) {
        Ok(s) => ctx.throw(s.into_value()),
        Err(e) => e,
    }
}

// --- Buffer ------------------------------------------------------------------------------

fn buffer_bridge<'js>(ctx: Ctx<'js>, req: Object<'js>) -> rquickjs::Result<Object<'js>> {
    let op: String = req.get("op")?;
    let encoding: String = req.get("encoding")?;
    let out = Object::new(ctx.clone())?;
    if op == "encode" {
        let input: String = req.get("input")?;
        let bytes = match encoding.as_str() {
            "utf8" | "utf-8" => input.into_bytes(),
            "hex" => hex::decode(&input).unwrap_or_default(),
            "base64" => base64::engine::general_purpose::STANDARD
                .decode(input.trim())
                .unwrap_or_default(),
            "base64url" => base64::engine::general_purpose::URL_SAFE_NO_PAD
                .decode(input.trim_end_matches('='))
                .unwrap_or_default(),
            "ascii" | "latin1" => input.chars().map(|c| c as u32 as u8).collect(),
            _ => return Err(throw(ctx, "Unsupported Buffer encoding in Safe mode")),
        };
        out.set("bytes", ArrayBuffer::new(ctx, bytes)?)?;
    } else {
        let bytes = bytes_of(&req, "bytes")?;
        let text = match encoding.as_str() {
            "utf8" | "utf-8" => String::from_utf8_lossy(&bytes).into_owned(),
            "hex" => hex::encode(&bytes),
            "base64" => base64::engine::general_purpose::STANDARD.encode(&bytes),
            "base64url" => base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(&bytes),
            "ascii" | "latin1" => bytes.iter().map(|b| *b as char).collect(),
            _ => return Err(throw(ctx, "Unsupported Buffer encoding in Safe mode")),
        };
        out.set("text", text)?;
    }
    Ok(out)
}

/// Read an ArrayBuffer (or TypedArray) property as bytes — how binary crosses the edge.
fn bytes_of<'js>(obj: &Object<'js>, key: &str) -> rquickjs::Result<Vec<u8>> {
    let v: JsValue<'js> = obj.get(key)?;
    if let Some(ab) = ArrayBuffer::from_value(v.clone()) {
        return Ok(ab.as_bytes().unwrap_or_default().to_vec());
    }
    if let Some(o) = v.as_object() {
        if let Ok(ab) = o.get::<_, ArrayBuffer<'js>>("buffer") {
            return Ok(ab.as_bytes().unwrap_or_default().to_vec());
        }
    }
    Ok(Vec::new())
}

// --- crypto ------------------------------------------------------------------------------

fn crypto_bridge<'js>(ctx: Ctx<'js>, req: Object<'js>) -> rquickjs::Result<Object<'js>> {
    use hmac::{KeyInit, Mac};
    let op: String = req.get("op")?;
    let out = Object::new(ctx.clone())?;
    match op.as_str() {
        "hash" => {
            let algo: String = req.get("algo")?;
            let data = bytes_of(&req, "data")?;
            let digest = match normalise_algo(&algo).as_str() {
                "md5" => {
                    use md5::Digest;
                    md5::Md5::digest(&data).to_vec()
                }
                "sha1" => {
                    use sha1::Digest;
                    sha1::Sha1::digest(&data).to_vec()
                }
                "sha256" => {
                    use sha2::Digest;
                    sha2::Sha256::digest(&data).to_vec()
                }
                "sha384" => {
                    use sha2::Digest;
                    sha2::Sha384::digest(&data).to_vec()
                }
                "sha512" => {
                    use sha2::Digest;
                    sha2::Sha512::digest(&data).to_vec()
                }
                other => return Err(throw(ctx, &format!("Unsupported hash algorithm '{other}'"))),
            };
            let encoding: String = req.get("outputEncoding").unwrap_or_else(|_| "hex".into());
            out.set("digest", encode_digest(&digest, &encoding))?;
        }
        "hmac" => {
            let algo: String = req.get("algo")?;
            let key = bytes_of(&req, "key")?;
            let data = bytes_of(&req, "data")?;
            let digest = match normalise_algo(&algo).as_str() {
                "sha256" => {
                    let mut m = <hmac::Hmac<sha2::Sha256> as KeyInit>::new_from_slice(&key)
                        .map_err(|_| throw(ctx.clone(), "invalid HMAC key"))?;
                    m.update(&data);
                    m.finalize().into_bytes().to_vec()
                }
                "sha512" => {
                    let mut m = <hmac::Hmac<sha2::Sha512> as KeyInit>::new_from_slice(&key)
                        .map_err(|_| throw(ctx.clone(), "invalid HMAC key"))?;
                    m.update(&data);
                    m.finalize().into_bytes().to_vec()
                }
                "sha1" => {
                    let mut m = <hmac::Hmac<sha1::Sha1> as KeyInit>::new_from_slice(&key)
                        .map_err(|_| throw(ctx.clone(), "invalid HMAC key"))?;
                    m.update(&data);
                    m.finalize().into_bytes().to_vec()
                }
                other => return Err(throw(ctx, &format!("Unsupported HMAC algorithm '{other}'"))),
            };
            let encoding: String = req.get("outputEncoding").unwrap_or_else(|_| "hex".into());
            out.set("digest", encode_digest(&digest, &encoding))?;
        }
        "randomBytes" => {
            let size: usize = req
                .get::<_, f64>("size")
                .unwrap_or(0.0)
                .clamp(0.0, 65_536.0) as usize;
            let mut bytes = vec![0u8; size];
            getrandom::fill(&mut bytes).map_err(|_| throw(ctx.clone(), "randomBytes failed"))?;
            out.set("bytes", ArrayBuffer::new(ctx, bytes)?)?;
        }
        "randomUUID" => {
            out.set("uuid", uuid::Uuid::new_v4().to_string())?;
        }
        other => return Err(throw(ctx, &format!("Unsupported crypto op '{other}'"))),
    }
    Ok(out)
}

fn normalise_algo(algo: &str) -> String {
    algo.to_ascii_lowercase().replace('-', "")
}

fn encode_digest(digest: &[u8], encoding: &str) -> String {
    match encoding {
        "base64" => base64::engine::general_purpose::STANDARD.encode(digest),
        "base64url" => base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(digest),
        "latin1" | "binary" => digest.iter().map(|b| *b as char).collect(),
        _ => hex::encode(digest),
    }
}

// --- zlib --------------------------------------------------------------------------------

fn zlib_bridge<'js>(ctx: Ctx<'js>, req: Object<'js>) -> rquickjs::Result<Object<'js>> {
    use flate2::read::{DeflateDecoder, DeflateEncoder, GzDecoder, GzEncoder};
    use std::io::Read;

    let op: String = req.get("op")?;
    let data = bytes_of(&req, "data")?;
    let level = flate2::Compression::default();
    let mut buf = Vec::new();
    let outcome = match op.as_str() {
        "deflate" => DeflateEncoder::new(&data[..], level).read_to_end(&mut buf),
        "inflate" => DeflateDecoder::new(&data[..]).read_to_end(&mut buf),
        "gzip" => GzEncoder::new(&data[..], level).read_to_end(&mut buf),
        "gunzip" => GzDecoder::new(&data[..]).read_to_end(&mut buf),
        other => return Err(throw(ctx, &format!("Unsupported zlib op '{other}'"))),
    };
    outcome.map_err(|e| throw(ctx.clone(), &format!("{op} failed: {e}")))?;
    let out = Object::new(ctx.clone())?;
    out.set("bytes", ArrayBuffer::new(ctx, buf)?)?;
    Ok(out)
}

// --- util.inspect ------------------------------------------------------------------------

/// Node's `util.inspect` over a pre-serialised value. This is the one bridge that
/// *approximates* rather than matches: node's formatter has many years of edge cases in it,
/// and the guest hands us JSON, so anything JSON dropped (functions, symbols, cycles) is
/// already gone before we see it. Objects and arrays are formatted node-style, which covers
/// what scripts actually inspect.
fn util_inspect_bridge<'js>(ctx: Ctx<'js>, req: Object<'js>) -> rquickjs::Result<Object<'js>> {
    let json: String = req.get("json").unwrap_or_default();
    let value: Value = serde_json::from_str(&json).unwrap_or(Value::String(json.clone()));
    let out = Object::new(ctx.clone())?;
    out.set("text", inspect(&value, 0))?;
    Ok(out)
}

fn inspect(value: &Value, depth: usize) -> String {
    match value {
        Value::Null => "null".into(),
        Value::Bool(b) => b.to_string(),
        Value::Number(n) => n.to_string(),
        Value::String(s) => format!("'{}'", s.replace('\'', "\\'")),
        _ if depth >= 4 => match value {
            Value::Array(_) => "[Array]".into(),
            _ => "[Object]".into(),
        },
        Value::Array(items) => {
            if items.is_empty() {
                return "[]".into();
            }
            let inner: Vec<String> = items.iter().map(|i| inspect(i, depth + 1)).collect();
            format!("[ {} ]", inner.join(", "))
        }
        Value::Object(map) => {
            if map.is_empty() {
                return "{}".into();
            }
            let inner: Vec<String> = map
                .iter()
                .map(|(k, v)| {
                    let key = if k
                        .chars()
                        .all(|c| c.is_alphanumeric() || c == '_' || c == '$')
                        && !k.is_empty()
                    {
                        k.clone()
                    } else {
                        format!("'{k}'")
                    };
                    format!("{key}: {}", inspect(v, depth + 1))
                })
                .collect();
            format!("{{ {} }}", inner.join(", "))
        }
    }
}

// --- fetch / sendRequest -----------------------------------------------------------------

fn fetch_bridge<'js>(ctx: Ctx<'js>, req: Object<'js>) -> rquickjs::Result<Object<'js>> {
    let url: String = req.get("url").unwrap_or_default();
    let method: String = req.get("method").unwrap_or_else(|_| "GET".into());
    let body: Option<String> = req.get("body").ok();
    let headers: Vec<(String, String)> = req
        .get::<_, Object<'js>>("headers")
        .map(|h| {
            h.keys::<String>()
                .filter_map(|k| k.ok())
                .filter_map(|k| h.get::<_, String>(&*k).ok().map(|v| (k, v)))
                .collect()
        })
        .unwrap_or_default();

    let reply = match http_call(&method, &url, &headers, body.as_deref()) {
        Ok(v) => v,
        Err(e) => return Err(throw(ctx, &format!("fetch failed: {e}"))),
    };
    let bytes = reply.body;

    let out = Object::new(ctx.clone())?;
    out.set("status", reply.status)?;
    out.set("statusText", reply.status_text)?;
    let hs = Object::new(ctx.clone())?;
    for (k, v) in &reply.headers {
        hs.set(k.to_ascii_lowercase(), v.as_str())?;
    }
    out.set("headers", hs)?;
    // Text when it is text; base64 otherwise — the shim decodes on that flag.
    match String::from_utf8(bytes.clone()) {
        Ok(text) => {
            out.set("body", text)?;
            out.set("bodyEncoding", "utf8")?;
        }
        Err(_) => {
            out.set(
                "body",
                base64::engine::general_purpose::STANDARD.encode(&bytes),
            )?;
            out.set("bodyEncoding", "base64")?;
        }
    }
    Ok(out)
}

/// `rq.sendRequest` — the same call, in the envelope the run-request shim expects.
fn run_request_bridge<'js>(
    ctx: Ctx<'js>,
    descriptor: Object<'js>,
) -> rquickjs::Result<Object<'js>> {
    let started = Instant::now();
    let url: String = descriptor.get("url").unwrap_or_default();
    let method: String = descriptor.get("method").unwrap_or_else(|_| "GET".into());
    let body: Option<String> = descriptor.get("body").ok();
    let headers: Vec<(String, String)> = descriptor
        .get::<_, Object<'js>>("headers")
        .map(|h| {
            h.keys::<String>()
                .filter_map(|k| k.ok())
                .filter_map(|k| h.get::<_, String>(&*k).ok().map(|v| (k, v)))
                .collect()
        })
        .unwrap_or_default();

    let out = Object::new(ctx.clone())?;
    match http_call(&method, &url, &headers, body.as_deref()) {
        Ok(reply) => {
            let r = Object::new(ctx.clone())?;
            r.set("code", reply.status)?;
            r.set("status", reply.status_text)?;
            r.set("responseTime", started.elapsed().as_millis() as f64)?;
            let hs = Object::new(ctx.clone())?;
            for (k, v) in &reply.headers {
                hs.set(k.as_str(), v.as_str())?;
            }
            r.set("headers", hs)?;
            r.set("body", String::from_utf8_lossy(&reply.body).into_owned())?;
            out.set("response", r)?;
        }
        Err(e) => {
            out.set("error", e.to_string())?;
        }
    }
    Ok(out)
}

/// What one HTTP call gives back: status, reason, headers, bytes.
struct HttpReply {
    status: u16,
    status_text: String,
    headers: Vec<(String, String)>,
    body: Vec<u8>,
}

/// One blocking HTTP call on the same client the rest of rq uses.
fn http_call(
    method: &str,
    url: &str,
    headers: &[(String, String)],
    body: Option<&str>,
) -> Result<HttpReply> {
    let agent = ureq::Agent::new_with_defaults();
    let mut builder = ureq::http::Request::builder()
        .method(method.to_ascii_uppercase().as_str())
        .uri(url);
    for (k, v) in headers {
        builder = builder.header(k.as_str(), v.as_str());
    }
    let request = builder
        .body(body.unwrap_or_default().to_string())
        .with_context(|| format!("building the request for {url}"))?;
    let mut resp = agent.run(request)?;
    let status = resp.status().as_u16();
    let status_text = resp.status().canonical_reason().unwrap_or("").to_string();
    let resp_headers: Vec<(String, String)> = resp
        .headers()
        .iter()
        .map(|(k, v)| {
            (
                k.as_str().to_string(),
                v.to_str().unwrap_or_default().to_string(),
            )
        })
        .collect();
    let bytes = resp.body_mut().read_to_vec()?;
    Ok(HttpReply {
        status,
        status_text,
        headers: resp_headers,
        body: bytes,
    })
}


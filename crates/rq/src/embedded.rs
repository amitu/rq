/// Raw guest mutations → the host-facing `MutationDiff`.
///
/// Ported rather than invented, rule for rule: an existing variable keeps its `syncValue`
/// and only its `localValue` moves; a **secret keeps its type**, so a script set can never
/// downgrade one to plaintext; a new runtime variable gets an empty `syncValue` because it
/// is transient; `null` means unset.
fn inflate_mutations(raw: &Value, context: &Value) -> Value {
    let mut diff = Map::new();
    if let Some(scope) = raw.get("global").filter(|v| !v.is_null()) {
        diff.insert(
            "global".into(),
            inflate_scope(scope, context.get("global"), false),
        );
    }
    if let Some(scope) = raw.get("environment").filter(|v| !v.is_null()) {
        diff.insert(
            "environment".into(),
            inflate_scope(scope, context.get("environment"), false),
        );
    }
    if let Some(scope) = raw.get("runtime").filter(|v| !v.is_null()) {
        diff.insert(
            "runtime".into(),
            inflate_scope(scope, context.get("variables"), true),
        );
    }
    if let Some(scope) = raw.get("collection").filter(|v| !v.is_null()) {
        if let Some(id) = context
            .get("info")
            .and_then(|i| i.get("collectionId"))
            .and_then(|c| c.as_str())
        {
            diff.insert(
                "collection".into(),
                json!({
                    "collectionId": id,
                    "variables": inflate_scope(scope, context.get("collectionVariables"), false),
                }),
            );
        }
    }
    Value::Object(diff)
}

fn inflate_scope(raw: &Value, context_vars: Option<&Value>, is_runtime: bool) -> Value {
    let mut out = Map::new();
    let Some(entries) = raw.as_object() else {
        return Value::Object(out);
    };
    for (key, entry) in entries {
        if entry.is_null() {
            out.insert(key.clone(), Value::Null);
            continue;
        }
        let value = entry.get("value").cloned().unwrap_or_else(|| json!(""));
        let raw_type = entry
            .get("type")
            .and_then(|t| t.as_str())
            .unwrap_or("string");
        let existing = context_vars
            .and_then(|v| v.get(key))
            .filter(|v| v.is_object());
        match existing {
            Some(existing) => {
                let mut merged = existing.as_object().cloned().unwrap_or_default();
                let is_secret = merged.get("type").and_then(|t| t.as_str()) == Some("secret");
                merged.insert("localValue".into(), value);
                if !is_secret {
                    merged.insert("type".into(), json!(raw_type));
                }
                out.insert(key.clone(), Value::Object(merged));
            }
            None => {
                let now = iso_now();
                out.insert(
                    key.clone(),
                    json!({
                        "id": uuid::Uuid::new_v4().to_string(),
                        "syncValue": if is_runtime { json!("") } else { value.clone() },
                        "localValue": value,
                        "type": raw_type,
                        "isEnabled": true,
                        "isPersisted": false,
                        "rank": Value::Null,
                        "createdAt": now, "updatedAt": now,
                        "createdBy": Value::Null, "updatedBy": Value::Null,
                    }),
                );
            }
        }
    }
    Value::Object(out)
}

fn now_millis() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

/// An ISO-8601 timestamp without pulling in a date library for one field.
fn iso_now() -> String {
    let secs = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let (days, rem) = ((secs / 86_400) as i64, secs % 86_400);
    // Howard Hinnant's civil_from_days.
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if m <= 2 { y + 1 } else { y };
    format!(
        "{y:04}-{m:02}-{d:02}T{:02}:{:02}:{:02}.000Z",
        rem / 3600,
        (rem % 3600) / 60,
        rem % 60
    )
}

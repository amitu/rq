/// `rq.cookies.jar(host)`, in memory for the run. A CLI process has no browser cookie store
/// to speak for, and inventing persistence would be claiming more than we do.
fn cookie_bridge<'js>(
    ctx: Ctx<'js>,
    args: Object<'js>,
    state: &Rc<RefCell<Collected>>,
) -> rquickjs::Result<Object<'js>> {
    let op: String = args.get("op").unwrap_or_default();
    let host: String = args.get("host").unwrap_or_default();
    let out = Object::new(ctx.clone())?;
    let mut st = state.borrow_mut();
    let jar = st
        .cookies
        .entry(host)
        .or_insert_with(|| Value::Array(Vec::new()));
    let list = jar.as_array_mut().expect("jar is an array");

    match op.as_str() {
        "list" => {
            let json = Value::Array(list.clone()).to_string();
            let parsed: JsValue<'js> = ctx.json_parse(json)?;
            out.set("result", parsed)?;
        }
        "upsert" => {
            let cookie: JsValue<'js> = args.get("cookie")?;
            let as_json: Value = serde_json::from_str(
                &ctx.json_stringify(cookie.clone())?
                    .and_then(|s| s.to_string().ok())
                    .unwrap_or_else(|| "null".into()),
            )
            .unwrap_or(Value::Null);
            let name = as_json
                .get("name")
                .and_then(|n| n.as_str())
                .unwrap_or_default()
                .to_string();
            list.retain(|c| c.get("name").and_then(|n| n.as_str()) != Some(name.as_str()));
            list.push(as_json);
            out.set("result", cookie)?;
        }
        "remove" => {
            let name: String = args.get("name").unwrap_or_default();
            list.retain(|c| c.get("name").and_then(|n| n.as_str()) != Some(name.as_str()));
            out.set("result", true)?;
        }
        "clear" => {
            list.clear();
            out.set("result", true)?;
        }
        _ => {
            out.set("error", "unknown cookie op")?;
        }
    }
    Ok(out)
}

